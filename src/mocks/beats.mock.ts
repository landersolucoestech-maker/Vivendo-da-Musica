export const getProducerBeatDashboard = (): ProducerBeatDashboard => {
  const totalSales = MOCK_BEATS.reduce((sum, beat) => sum + beat.sales, 0);
  const totalRevenueCents = MOCK_BEATS.reduce((sum, beat) => sum + beat.revenueCents, 0);
  const totalViews = MOCK_BEATS.reduce((sum, beat) => sum + beat.views, 0);
  const totalPlays = MOCK_BEATS.reduce((sum, beat) => sum + beat.plays, 0);

  return {
    financial: {
      availableBalanceCents: 0,
      eligibleBalanceCents: 0,
      nextEligibilityAt: null,
      currency: "BRL",
      commissionBps: 1500,
      payoutMinimumCents: 10000,
      payoutDelayDays: 14,
      payoutMethods: [],
      payoutRequests: [],
    },
    totals: {
      totalSales,
      totalRevenueCents,
      totalViews,
      totalPlays,
      averageConversionRate: totalPlays ? Number(((totalSales / totalPlays) * 100).toFixed(2)) : 0,
    },
    ranking: [...MOCK_BEATS].sort((a, b) => b.sales - a.sales),
    transactions: MOCK_BEAT_TRANSACTIONS,
    beats: MOCK_BEATS,
  };
};
